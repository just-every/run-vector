import assert from "node:assert/strict";
import { auditBothWidths, settled } from "./ui-state-audit.mjs";
import { browserReceipt } from "./issue-controls-fixture.mjs";

export async function exerciseSearch(context,fixture){
  const {page,base}=context;
  const {api,a}=fixture;
  await page.goto(base+`/app/issues/${a.identifier}`);
  await settled(page);
  const phrase="quartz lagoon searchable comment";
  await page.getByLabel("Add a comment",{exact:true}).fill(phrase);
  await browserReceipt(page,`/api/issues/${a.identifier}/comments`,"POST",()=>page.getByRole("button",{name:"Add comment",exact:true}).click(),201);
  await auditBothWidths(context,"search-comment-written");
  await page.goto(base+"/app/search");
  await page.getByRole("heading",{name:"Search",exact:true}).waitFor();
  await auditBothWidths(context,"search-resting");
  const start=Date.now();
  await page.getByLabel("Search workspace",{exact:true}).fill(phrase);
  await page.getByRole("link",{name:new RegExp(a.identifier)}).waitFor({timeout:10000});
  assert.ok(Date.now()-start<10000,"SEARCH-003 newly written comment indexed within ten seconds");
  await auditBothWidths(context,"search-fresh-comment-results");
  await page.getByRole("link",{name:new RegExp(a.identifier)}).click();
  await settled(page);
  await page.getByRole("button",{name:"Edit comment",exact:true}).click();
  const revised="cobalt orchard revised comment";
  await page.getByLabel("Edit comment",{exact:true}).fill(revised);
  await page.getByRole("button",{name:"Save comment",exact:true}).click();
  await page.getByText(revised,{exact:true}).waitFor();
  await auditBothWidths(context,"search-comment-edited");
  await page.goto(base+"/app/search");
  await page.getByLabel("Search workspace",{exact:true}).fill(revised);
  await page.getByRole("link",{name:new RegExp(a.identifier)}).waitFor({timeout:10000});
  assert.ok((await api(`/api/search?q=${encodeURIComponent(revised)}`)).issues.some(row=>row.identifier===a.identifier),"SEARCH-003 edited comment appears");
  assert.equal((await api(`/api/search?q=${encodeURIComponent(phrase)}`)).issues.some(row=>row.identifier===a.identifier),false,"SEARCH-003 removed comment text no longer indexed");
  await auditBothWidths(context,"search-edited-comment-results");
  const project=(await api(`/api/issues/${a.identifier}`)).project;
  assert.ok(project,"fixture search issue belongs to a project");
  await api(`/api/settings/projects/${project.id}`,"PATCH",{archived:true});
  await page.getByLabel("Search workspace",{exact:true}).fill("archived search temporary term");
  await page.getByLabel("Search workspace",{exact:true}).fill(revised);
  await page.getByRole("heading",{name:"No results",exact:true}).waitFor();
  assert.equal((await api(`/api/search?q=${encodeURIComponent(revised)}`)).issues.some(row=>row.identifier===a.identifier),false,"SEARCH-001 archived project issue hidden by default");
  await auditBothWidths(context,"search-archived-project-excluded");
  await page.getByLabel("Include archived teams and projects",{exact:true}).check();
  await page.getByRole("link",{name:new RegExp(a.identifier)}).waitFor();
  assert.ok((await api(`/api/search?q=${encodeURIComponent(revised)}&includeArchived=true`)).issues.some(row=>row.identifier===a.identifier),"SEARCH-001 archived checkbox includes issue");
  await settled(page);
  await auditBothWidths(context,"search-include-archived");
  await page.getByLabel("Search workspace",{exact:true}).fill("unmatched krypton fern phrase");
  await page.getByRole("heading",{name:"No results",exact:true}).waitFor();
  await auditBothWidths(context,"search-no-results");
  await api(`/api/settings/projects/${project.id}`,"PATCH",{archived:false});
}
