import assert from "node:assert/strict";
import { auditBothWidths, settled } from "./ui-state-audit.mjs";
import { browserReceipt } from "./issue-controls-fixture.mjs";

async function chooseParent(page, identifier) {
  const hierarchy=page.getByRole("region",{name:"Issue hierarchy",exact:true});
  await hierarchy.getByLabel("Search parent issues",{exact:true}).fill(identifier);
  await hierarchy.getByRole("button",{name:"Search",exact:true}).click();
  await hierarchy.getByRole("button",{name:new RegExp(identifier)}).waitFor();
  await hierarchy.getByRole("button",{name:new RegExp(identifier)}).click();
}
export async function exerciseParents(context,fixture,peer){
  const {page,base}=context;
  const {api,a,b,done,started}=fixture;
  await page.goto(base+`/app/issues/${a.identifier}`);
  await settled(page);
  const hierarchy=page.getByRole("region",{name:"Issue hierarchy",exact:true});
  await hierarchy.getByRole("button",{name:"Set parent",exact:true}).click();
  await auditBothWidths(context,"parent-editor-empty");
  await hierarchy.getByLabel("Search parent issues",{exact:true}).fill(a.identifier);
  await hierarchy.getByRole("button",{name:"Search",exact:true}).click();
  await hierarchy.getByText("No matching issues. Try another identifier or title.",{exact:true}).waitFor();
  assert.equal(await hierarchy.getByRole("button",{name:new RegExp(a.identifier)}).count(),0,"REL-006 own issue never a parent choice");
  const selfBefore=await api(`/api/issues/${a.identifier}`);
  await api(`/api/issues/${a.identifier}/parent`,"PATCH",{expectedVersion:selfBefore.version,parentIdentifier:a.identifier},400);
  assert.equal((await api(`/api/issues/${a.identifier}`)).version,selfBefore.version,"REL-006 self-parent refused without writes");
  await auditBothWidths(context,"parent-self-excluded");
  await chooseParent(page,b.identifier);
  await auditBothWidths(context,"parent-search-selected");
  const beforeParent=await api(`/api/issues/${a.identifier}`);
  await browserReceipt(page,`/api/issues/${a.identifier}/parent`,"PATCH",()=>hierarchy.getByRole("button",{name:"Save parent",exact:true}).click());
  const afterParent=await api(`/api/issues/${a.identifier}`);
  for(const field of ["status","team","project","cycle","assignee"])assert.deepEqual(afterParent[field],beforeParent[field],`REL-006 setting parent preserves ${field}`);
  assert.equal(afterParent.parent.identifier,b.identifier,"REL-006 set parent persisted");
  await auditBothWidths(context,"parent-set");
  await page.goto(base+`/app/issues/${b.identifier}`);
  await settled(page);
  await page.getByRole("region",{name:"Issue hierarchy",exact:true}).getByLabel("Children (1)",{exact:true}).click();
  await page.getByRole("link",{name:new RegExp(`Child ${a.identifier}:.*status ${afterParent.status.name}`)}).waitFor();
  await auditBothWidths(context,"parent-children-status");
  await page.goto(base+`/app/issues/${a.identifier}`);
  await settled(page);
  await hierarchy.getByRole("button",{name:"Change parent",exact:true}).click();
  await chooseParent(page,done.identifier);
  await browserReceipt(page,`/api/issues/${a.identifier}/parent`,"PATCH",()=>hierarchy.getByRole("button",{name:"Save parent",exact:true}).click());
  assert.equal((await api(`/api/issues/${a.identifier}`)).parent.status.category,"completed","REL-006 completed parent is selectable with status");
  await auditBothWidths(context,"parent-changed-completed");
  await hierarchy.getByRole("button",{name:"Change parent",exact:true}).click();
  await browserReceipt(page,`/api/issues/${a.identifier}/parent`,"PATCH",()=>hierarchy.getByRole("button",{name:"Clear parent",exact:true}).click());
  assert.equal((await api(`/api/issues/${a.identifier}`)).parent,null,"REL-006 clear parent persisted");
  await auditBothWidths(context,"parent-cleared");
  const child=await api(`/api/issues/${b.identifier}`);
  await api(`/api/issues/${b.identifier}/parent`,"PATCH",{expectedVersion:child.version,parentIdentifier:a.identifier});
  await hierarchy.getByRole("button",{name:"Set parent",exact:true}).click();
  await chooseParent(page,b.identifier);
  await browserReceipt(page,`/api/issues/${a.identifier}/parent`,"PATCH",()=>hierarchy.getByRole("button",{name:"Save parent",exact:true}).click(),400);
  await hierarchy.getByText("This parent would create a cycle.",{exact:true}).waitFor();
  assert.equal((await api(`/api/issues/${a.identifier}`)).parent,null,"REL-006 cycle refusal wrote nothing");
  await auditBothWidths(context,"parent-cycle-refused");
  await hierarchy.getByRole("button",{name:"Cancel",exact:true}).click();
  await hierarchy.getByRole("button",{name:"Set parent",exact:true}).click();
  await chooseParent(page,done.identifier);
  const staleBefore=await api(`/api/issues/${a.identifier}`);
  await peer.api(`/api/issues/${a.identifier}`,"PATCH",{expectedVersion:staleBefore.version,priority:"low"});
  const stale=await browserReceipt(page,`/api/issues/${a.identifier}/parent`,"PATCH",()=>hierarchy.getByRole("button",{name:"Save parent",exact:true}).click(),409);
  assert.equal(stale.error,"stale_version");
  await hierarchy.getByRole("button",{name:"Refresh issue",exact:true}).waitFor();
  assert.match(await hierarchy.getByRole("status").first().textContent(),new RegExp(done.identifier),"ISSUE-006 stale keeps chosen parent");
  await auditBothWidths(context,"parent-stale-choice-retained");
  await hierarchy.getByRole("button",{name:"Refresh issue",exact:true}).click();
  await browserReceipt(page,`/api/issues/${a.identifier}/parent`,"PATCH",()=>hierarchy.getByRole("button",{name:"Save parent",exact:true}).click());
  await page.reload();await settled(page);
  await hierarchy.getByRole("link",{name:new RegExp(`Parent ${done.identifier}:`)}).waitFor();
  await auditBothWidths(context,"parent-refreshed-and-reloaded");
  await page.goto(base+"/app/issues");
  await settled(page);
  await page.getByLabel("Parent",{exact:true}).selectOption("identifier");
  await page.getByLabel("Parent identifier",{exact:true}).fill("invalid");
  await page.getByRole("button",{name:"Apply parent",exact:true}).click();
  await page.getByText("Enter a valid parent identifier, such as ENG-1.",{exact:true}).waitFor();
  await auditBothWidths(context,"issues-parent-filter-invalid-draft");
  await page.getByLabel("Parent identifier",{exact:true}).fill(done.identifier);
  await page.getByRole("button",{name:"Apply parent",exact:true}).click();
  await settled(page);
  await page.locator(`#issue-row-${a.identifier}`).waitFor();
  const children=await api("/api/issues"+new URL(page.url()).search);
  assert.deepEqual(children.issues.map(row=>row.identifier),[a.identifier],"VIEW-001 exact parent control filters children");
  await auditBothWidths(context,"issues-exact-parent-filter");
  await page.getByRole("button",{name:"Reset controls",exact:true}).click();
}

