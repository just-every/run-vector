import {env} from 'cloudflare:workers';
import {expect} from 'vitest';
import type {collaborationFixture} from './collaboration-fixture';
export async function exerciseSubjectSubscriptions(f:Awaited<ReturnType<typeof collaborationFixture>>){
 const read=async(response:Response,status=200)=>{expect(response.status,await response.clone().text()).toBe(status);return response.json() as Promise<any>;};
 const bob=(path:string,method='GET',body?:unknown)=>f.any(f.bobCookie,path,method,body);
 const cara=(path:string,method='GET',body?:unknown)=>f.any(f.caraCookie,path,method,body);
 const team=f.initial.teams[0];
 await read(await bob('/settings/notifications','PATCH',{mutedKinds:[],emailEnabled:true}));
 await read(await bob('/settings/notifications/channels','PUT',{channels:[{kind:'status',emailMode:'immediate',slack:false},{kind:'completed',emailMode:'immediate',slack:false}]}));
 await read(await bob('/teams/'+team.id+'/join','POST',{}));
 const labelState=await read(await f.call('/settings/labels','POST',{name:'synthetic-vector-1760',color:'#3355aa'}));
 const label=labelState.labels.find((l:any)=>l.name==='synthetic-vector-1760');
 const projectState=await read(await f.call('/settings/projects','POST',{name:'synthetic-vector-1761',leadOperatorId:f.owner}));
 const project=projectState.projects.find((p:any)=>p.name==='synthetic-vector-1761');
 const view=await read(await f.call('/views','POST',{name:'synthetic-vector-1762',isShared:true,query:{team:team.id,label:label.id}}),201);
 const subjects=[['team',team.id],['project',project.id],['label',label.id],['view',view.id]];
 const subscriptions=[];
 for(const [subjectType,subjectId] of subjects)subscriptions.push(await read(await bob('/subscriptions','POST',{subjectType,subjectId}),201));
 const same=await read(await bob('/subscriptions','POST',{subjectType:'label',subjectId:label.id}),201);expect(same.id).toBe(subscriptions[2].id);
 expect((await cara('/subscriptions/'+same.id,'DELETE')).status).toBe(404);
 expect((await bob('/subscriptions?operatorId='+f.owner)).status).toBe(400);
 expect((await bob('/subscriptions','POST',{subjectType:'label',subjectId:label.id,operatorId:f.owner})).status).toBe(400);
 await read(await f.call('/subscriptions','POST',{subjectType:'label',subjectId:label.id}),201);
 const first=await f.create({title:'synthetic-vector-1763',labelIds:[label.id],projectId:project.id});
 const notices=async(call:typeof bob,identifier:string)=>(await read(await call('/notifications?limit=50'))).items.filter((n:any)=>n.identifier===identifier);
 let rows=await notices(bob,first.identifier);expect(rows).toHaveLength(1);expect(rows[0]).toMatchObject({sourceEventKind:'issue.created',causes:['status']});
 expect(await notices((p,m,b)=>f.call(p,m,b),first.identifier)).toHaveLength(0);
 expect(await notices(bob,first.identifier)).toHaveLength(1);
 const deliveries=async()=>env.DB.prepare('SELECT status FROM notification_deliveries WHERE notification_id IN(SELECT id FROM notifications WHERE issue_id=? AND recipient_id=?)').bind(first.id,f.bob).all();
 expect((await deliveries()).results).toHaveLength(1);expect((await deliveries()).results[0]).toMatchObject({status:'development'});
 expect((await f.call('/settings/operators/'+f.cara+'/role','PATCH',{role:'guest',teamIds:[team.id]})).status).toBe(200);
 await read(await cara('/settings/notifications','PATCH',{mutedKinds:[],emailEnabled:false}));
 await read(await cara('/subscriptions','POST',{subjectType:'project',subjectId:project.id}),201);
 const started=team.statuses.find(s=>s.category==='started')!;
 const moved=await read(await f.call('/issues/'+first.identifier,'PATCH',{expectedVersion:first.version,statusId:started.id}));
 rows=await notices(bob,first.identifier);expect(rows).toHaveLength(2);expect(await notices(cara,first.identifier)).toHaveLength(1);
 expect(await notices(bob,first.identifier)).toHaveLength(2);
 const hiddenState=await read(await f.call('/settings/teams','POST',{name:'synthetic-vector-1764',identifierPrefix:'SUBHID'}));
 const hiddenTeam=hiddenState.teams.find((t:any)=>t.name==='synthetic-vector-1764');
 expect((await cara('/subscriptions','POST',{subjectType:'team',subjectId:hiddenTeam.id})).status).toBe(404);
 const hidden=await f.create({title:'synthetic-vector-1765',teamId:hiddenTeam.id,labelIds:[label.id],projectId:project.id});
 expect(await notices(cara,hidden.identifier)).toHaveLength(0);
 for(const sub of subscriptions)await read(await bob('/subscriptions/'+sub.id,'DELETE'));
 const second=await f.create({title:'synthetic-vector-1766',labelIds:[label.id],projectId:project.id});expect(await notices(bob,second.identifier)).toHaveLength(0);
 // A fresh subscription never backfills the second issue.
 const teamSub=await read(await bob('/subscriptions','POST',{subjectType:'team',subjectId:team.id}),201);
 expect(await notices(bob,second.identifier)).toHaveLength(0);
 const third=await f.create({title:'synthetic-vector-1767'});expect(await notices(bob,third.identifier)).toHaveLength(1);
 await read(await bob('/teams/'+team.id+'/leave','POST',{}));
 expect((await read(await bob('/subscriptions'))).subscriptions.some((s:any)=>s.id===teamSub.id)).toBe(false);
 const fourth=await f.create({title:'synthetic-vector-1768'});expect(await notices(bob,fourth.identifier)).toHaveLength(0);
 await read(await bob('/subscriptions','POST',{subjectType:'label',subjectId:label.id}),201);
 expect((await f.call('/settings/operators/'+f.bob,'DELETE')).status).toBe(200);
 expect(await env.DB.prepare('SELECT count(*) AS n FROM subject_subscriptions WHERE operator_id=?').bind(f.bob).first<number>('n')).toBe(0);
 expect(moved.status.id).toBe(started.id);
}
