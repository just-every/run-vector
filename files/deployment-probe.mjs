import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
const root=process.cwd(),load=path=>import(pathToFileURL(resolve(root,path)).href);
const require=createRequire(pathToFileURL(resolve(root,'package.json')));
const rer=path=>import(pathToFileURL(require.resolve('@runeditrun/rer/internal/modules/deploy-kit/'+path)).href);
const {validateMigrations,migrate}=await rer('migrations.mjs');
const {cloudflare}=await rer('provider.mjs');
const {providerFixture}=await load('scripts/deployment/tests/cloudflare-edge/index.mjs');
const spec=JSON.parse(await readFile('management/integration/deployment-spec.json','utf8'));
const migrations=spec.migrations.map(({binding,...migration})=>migration);
const name='0126_gitlab_setup.sql',selected=migrations.find(migration=>migration.name===name);
assert.ok(selected,'GitLab setup migration is present in the hosted deployment recipe');
const bytes=await readFile('migrations/core/'+name,'utf8');
assert.equal(selected.sql,bytes,'the recipe retains exact applied migration bytes');
assert.equal(selected.sha256,createHash('sha256').update(bytes).digest('hex'));
validateMigrations(migrations);
const fixture=providerFixture();
try{
 const api=cloudflare({...fixture,budgetMigrations:true});
 const database=await api.request('/d1/database',{method:'POST',body:{name:'synthetic-vector-deployment-repair'}});
 const first=await migrate(api,database.uuid,migrations);
 const db=fixture.state.databases[0].db;
 const tables=db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name LIKE 'vector_gitlab_%' ORDER BY name").all().map(row=>row.name);
 assert.deepEqual(tables,['vector_gitlab_connections','vector_gitlab_hooks','vector_gitlab_projects']);
 const ledger=db.prepare('SELECT name,sha256,state FROM d1_migrations WHERE name=?').get(name);
 assert.deepEqual({...ledger},{name,sha256:selected.sha256,state:'applied'});
 const before=fixture.state.writes.length;
 const repeat=await migrate(api,database.uuid,migrations);
 assert.deepEqual(repeat.applied,[]);
 assert.equal(fixture.state.writes.length,before);
 assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
 const receipt={head:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),dirty:execFileSync('git',['status','--porcelain'],{encoding:'utf8'}).trim()!=='',command:'node ../deployment-probe.mjs',migrationCount:migrations.length,appliedCount:first.applied.length,gitlabTables:tables,migration:{...ledger},repeatApplied:repeat.applied,repeatProviderWrites:fixture.state.writes.length-before,foreignKeyViolations:0,exit:0};
 await writeFile('../packet/deployment-probe.json',JSON.stringify(receipt,null,2)+'\n');
 console.log(JSON.stringify(receipt,null,2));
}finally{await fixture.close();}
